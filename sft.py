#!/usr/bin/env python3
"""
Supervised Fine-Tuning (SFT) for GPT Language Models.

Transforms a pre-trained base text-continuation model into an instruction-following assistant.

Core SFT Mechanics:
  1. Chat template: User prompt and Assistant response.
  2. Prompt Loss Masking: Tokens belonging to the User prompt are masked with -100
     so cross-entropy loss is computed ONLY on the assistant's response tokens.
  3. Conservative Optimization: Uses a small learning rate (e.g. 2e-5) to preserve
     pre-trained language representations while learning turn-taking.

Usage:
  python sft.py --base_checkpoint checkpoints_medium/checkpoint-best.pt \
      --data_dir data/sft --max_steps 1000 --batch_size 8 --grad_accum 2
"""

from __future__ import annotations

import argparse
import contextlib
import json
import math
import os
import random
import sys
import time
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import torch
import torch.nn as nn
import torch.nn.functional as F
from torch.utils.data import DataLoader, Dataset
from tokenizers import Tokenizer

from model import IGNORE_INDEX, GPTConfig, GPTModel, clean_state_dict


def log(msg: str):
    print(msg, flush=True)


def pick_device(name: str) -> torch.device:
    if name == "auto":
        if torch.cuda.is_available():
            return torch.device("cuda")
        if getattr(torch.backends, "mps", None) and torch.backends.mps.is_available():
            return torch.device("mps")
        return torch.device("cpu")
    return torch.device(name)


def pick_precision(requested: str, device: torch.device) -> Optional[torch.dtype]:
    if requested == "fp32":
        return None
    if requested == "auto":
        if device.type != "cuda":
            return None
        return torch.bfloat16 if torch.cuda.is_bf16_supported() else torch.float16
    return {"bf16": torch.bfloat16, "fp16": torch.float16}[requested]


# --------------------------------------------------------------------------------------------
# Dataset with Prompt Loss Masking
# --------------------------------------------------------------------------------------------

class SFTDataset(Dataset):
    """Instruction dataset with token-level prompt masking.
    
    Tokens corresponding to 'User: ... \\nAssistant: ' are masked in `labels` with IGNORE_INDEX (-100).
    Only tokens generated by the Assistant are supervised.
    """
    def __init__(self, jsonl_path: Path, tokenizer: Tokenizer, max_length: int = 512):
        self.samples = []
        eos_id = tokenizer.token_to_id("</s>") or 3
        pad_id = tokenizer.token_to_id("<pad>") or 0

        with open(jsonl_path, "r", encoding="utf-8") as f:
            for line in f:
                if not line.strip():
                    continue
                data = json.loads(line)
                prompt = data["prompt"]
                response = data["response"]
                full_text = f"{prompt}{response}</s>"

                prompt_ids = tokenizer.encode(prompt, add_special_tokens=False).ids
                full_ids = tokenizer.encode(full_text, add_special_tokens=False).ids

                # Ensure EOS token is at the end
                if not full_ids or full_ids[-1] != eos_id:
                    full_ids.append(eos_id)

                if len(full_ids) > max_length:
                    full_ids = full_ids[:max_length]
                    if prompt_ids and len(prompt_ids) >= max_length:
                        continue  # Prompt took up the entire window

                # Labels: mask prompt tokens with -100
                labels = list(full_ids)
                prompt_len = min(len(prompt_ids), len(labels))
                for i in range(prompt_len):
                    labels[i] = IGNORE_INDEX

                # Verify that at least one response token is supervised
                if all(l == IGNORE_INDEX for l in labels):
                    continue

                self.samples.append({
                    "input_ids": full_ids,
                    "labels": labels,
                })

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> dict:
        return self.samples[idx]


def sft_collate_fn(batch: List[dict], pad_id: int = 0) -> dict:
    """Pad batch dynamically to the maximum sequence length in the batch."""
    max_len = max(len(x["input_ids"]) for x in batch)
    B = len(batch)

    input_ids = torch.full((B, max_len), fill_value=pad_id, dtype=torch.long)
    labels = torch.full((B, max_len), fill_value=IGNORE_INDEX, dtype=torch.long)

    for i, item in enumerate(batch):
        seq_len = len(item["input_ids"])
        input_ids[i, :seq_len] = torch.tensor(item["input_ids"], dtype=torch.long)
        labels[i, :seq_len] = torch.tensor(item["labels"], dtype=torch.long)

    return {"input_ids": input_ids, "labels": labels}


# --------------------------------------------------------------------------------------------
# In-Training Generation Probe
# --------------------------------------------------------------------------------------------

@torch.no_grad()
def probe_generation(model: GPTModel, tokenizer: Tokenizer, device: torch.device, prompt: str, max_new_tokens: int = 60) -> str:
    """Greedy/low-temp generation probe to monitor instruction following during training."""
    model.eval()
    eos_id = tokenizer.token_to_id("</s>") or 3
    input_ids = tokenizer.encode(prompt, add_special_tokens=False).ids
    if not input_ids:
        return ""
    x = torch.tensor([input_ids], dtype=torch.long, device=device)

    generated = list(input_ids)
    for _ in range(max_new_tokens):
        if x.shape[1] > model.config.max_length:
            break
        logits = model(x)["logits"][:, -1, :]  # (1, vocab_size)
        next_token = torch.argmax(logits, dim=-1).unsqueeze(0)  # (1, 1)
        next_id = int(next_token.item())
        generated.append(next_id)
        if next_id == eos_id:
            break
        x = torch.cat([x, next_token], dim=1)

    response_text = tokenizer.decode(generated[len(input_ids):], skip_special_tokens=True)
    return response_text.strip()


# --------------------------------------------------------------------------------------------
# Training Loop
# --------------------------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description="Supervised Fine-Tuning (SFT) for GPT")
    parser.add_argument("--base_checkpoint", type=str, default="checkpoints_medium/checkpoint-best.pt",
                        help="Path to pre-trained base model checkpoint")
    parser.add_argument("--data_dir", type=str, default="data/sft",
                        help="Directory containing train.jsonl and val.jsonl")
    parser.add_argument("--out_dir", type=str, default="checkpoints_sft",
                        help="Output directory for SFT checkpoints")
    parser.add_argument("--device", type=str, default="auto", choices=["auto", "cuda", "mps", "cpu"])
    parser.add_argument("--precision", type=str, default="auto", choices=["auto", "fp32", "fp16", "bf16"])
    parser.add_argument("--lr", type=float, default=2e-5, help="Learning rate (conservative for SFT)")
    parser.add_argument("--batch_size", type=int, default=8)
    parser.add_argument("--grad_accum", type=int, default=2, help="Gradient accumulation steps")
    parser.add_argument("--max_steps", type=int, default=1000, help="Total SFT training steps")
    parser.add_argument("--warmup_steps", type=int, default=50)
    parser.add_argument("--weight_decay", type=float, default=0.01)
    parser.add_argument("--grad_clip", type=float, default=1.0)
    parser.add_argument("--eval_interval", type=int, default=100)
    parser.add_argument("--save_interval", type=int, default=250)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    random.seed(args.seed)
    torch.manual_seed(args.seed)

    device = pick_device(args.device)
    dtype = pick_precision(args.precision, device)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    log(f"============================================================")
    log(f"🚀 Initializing Supervised Fine-Tuning (SFT)")
    log(f"   Base Checkpoint: {args.base_checkpoint}")
    log(f"   Device: {device} | Precision: {dtype or 'fp32'}")
    log(f"   Learning Rate: {args.lr} | Max Steps: {args.max_steps}")
    log(f"   Batch Size: {args.batch_size} (Grad Accum: {args.grad_accum})")
    log(f"============================================================")

    # Load Base Checkpoint
    if not Path(args.base_checkpoint).exists():
        raise FileNotFoundError(f"Base checkpoint not found at: {args.base_checkpoint}")

    ckpt = torch.load(args.base_checkpoint, map_location="cpu", weights_only=False)
    if "model_config" not in ckpt:
        raise ValueError("Checkpoint does not contain 'model_config'")

    cfg = GPTConfig.from_dict(ckpt["model_config"])
    log(f"✓ Model Architecture: {cfg.layers} layers, {cfg.heads} heads, dim {cfg.dim}, vocab {cfg.vocab_size}")

    model = GPTModel(cfg)
    model.load_state_dict(clean_state_dict(ckpt["model_state_dict"]))
    model.to(device)
    log(f"✓ Base model weights loaded successfully ({model.count_parameters():,} parameters).")

    # Load Tokenizer
    if "tokenizer" in ckpt:
        tokenizer = Tokenizer.from_str(ckpt["tokenizer"])
    else:
        tokenizer = Tokenizer.from_file("tokenizer/tokenizer.json")
    pad_id = tokenizer.token_to_id("<pad>") or 0

    # Datasets
    data_dir = Path(args.data_dir)
    train_dataset = SFTDataset(data_dir / "train.jsonl", tokenizer, max_length=cfg.max_length)
    val_dataset = SFTDataset(data_dir / "val.jsonl", tokenizer, max_length=cfg.max_length)
    log(f"✓ Datasets loaded: {len(train_dataset):,} train samples, {len(val_dataset):,} val samples.")

    train_loader = DataLoader(
        train_dataset,
        batch_size=args.batch_size,
        shuffle=True,
        collate_fn=lambda b: sft_collate_fn(b, pad_id=pad_id),
        drop_last=True
    )
    val_loader = DataLoader(
        val_dataset,
        batch_size=args.batch_size,
        shuffle=False,
        collate_fn=lambda b: sft_collate_fn(b, pad_id=pad_id),
        drop_last=False
    )

    # Optimizer & LR Schedule
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=args.weight_decay)

    def get_lr(step: int) -> float:
        if step < args.warmup_steps:
            return args.lr * (step + 1) / args.warmup_steps
        if step > args.max_steps:
            return args.lr * 0.1
        decay_ratio = (step - args.warmup_steps) / max(1, args.max_steps - args.warmup_steps)
        coeff = 0.5 * (1.0 + math.cos(math.pi * decay_ratio))
        return args.lr * 0.1 + coeff * (args.lr * 0.9)

    amp_ctx = (
        torch.autocast(device_type=device.type, dtype=dtype)
        if dtype and device.type in ("cuda", "cpu")
        else contextlib.nullcontext()
    )

    # Probe Prompts to track alignment evolution
    test_prompts = [
        "User: What is the opposite of cold?\nAssistant: ",
        "User: Give three tips for staying healthy.\nAssistant: ",
        "User: Write a 2-sentence story about a friendly bear.\nAssistant: ",
    ]

    log("\n📝 Pre-SFT Baseline Responses:")
    for tp in test_prompts:
        baseline_resp = probe_generation(model, tokenizer, device, tp)
        log(f"  • Q: {tp.splitlines()[0]}")
        log(f"    A: {baseline_resp[:120]}...\n")

    log("🎯 Starting SFT Training Loop...")
    step = 0
    epoch = 0
    best_val_loss = float("inf")
    train_iter = iter(train_loader)
    train_log_path = out_dir / "sft_log.jsonl"

    t0 = time.time()
    while step < args.max_steps:
        model.train()
        optimizer.zero_grad(set_to_none=True)
        accum_loss = 0.0

        for _ in range(args.grad_accum):
            try:
                batch = next(train_iter)
            except StopIteration:
                epoch += 1
                train_iter = iter(train_loader)
                batch = next(train_iter)

            input_ids = batch["input_ids"].to(device)
            labels = batch["labels"].to(device)

            with amp_ctx:
                out = model(input_ids, labels=labels)
                loss = out["loss"]
                scaled_loss = loss / args.grad_accum

            scaled_loss.backward()
            accum_loss += loss.item() / args.grad_accum

        torch.nn.utils.clip_grad_norm_(model.parameters(), args.grad_clip)

        # Update LR
        cur_lr = get_lr(step)
        for param_group in optimizer.param_groups:
            param_group["lr"] = cur_lr

        optimizer.step()
        step += 1

        # Periodic Logging
        if step % 20 == 0 or step == 1:
            dt = time.time() - t0
            tok_per_s = (args.batch_size * args.grad_accum * 128 * 20) / max(1e-5, dt) if step > 1 else 0
            ppl = math.exp(min(20.0, accum_loss))
            log(f"Step {step:4d}/{args.max_steps} | SFT Loss: {accum_loss:.4f} | PPL: {ppl:5.2f} | LR: {cur_lr:.2e}")
            with open(train_log_path, "a") as f:
                f.write(json.dumps({"step": step, "loss": accum_loss, "ppl": ppl, "lr": cur_lr}) + "\n")
            t0 = time.time()

        # Periodic Evaluation & Live Generation Probing
        if step % args.eval_interval == 0 or step == args.max_steps:
            model.eval()
            val_loss = 0.0
            val_batches = 0
            with torch.no_grad():
                for v_batch in val_loader:
                    v_in = v_batch["input_ids"].to(device)
                    v_lab = v_batch["labels"].to(device)
                    with amp_ctx:
                        v_loss = model(v_in, labels=v_lab)["loss"]
                    val_loss += v_loss.item()
                    val_batches += 1
                    if val_batches >= 25:
                        break

            val_loss /= max(1, val_batches)
            val_ppl = math.exp(min(20.0, val_loss))
            log(f"\n  🔍 [Eval Step {step}] Val Loss: {val_loss:.4f} | Val PPL: {val_ppl:.2f}")

            # Live generation test
            sample_ans = probe_generation(model, tokenizer, device, test_prompts[0])
            log(f"     Sample Generation -> Q: What is the opposite of cold?")
            log(f"                          A: {sample_ans}\n")

            if val_loss < best_val_loss:
                best_val_loss = val_loss
                best_ckpt_path = out_dir / "checkpoint-best.pt"
                torch.save({
                    "step": step,
                    "model_state_dict": model.state_dict(),
                    "model_config": cfg.to_dict(),
                    "tokenizer": tokenizer.to_str(),
                    "best_val_loss": best_val_loss,
                    "stage": "sft"
                }, best_ckpt_path)
                log(f"  ⭐ Saved new best SFT checkpoint (val_loss={best_val_loss:.4f})")

        # Periodic Saving
        if step % args.save_interval == 0:
            save_path = out_dir / f"checkpoint-{step}.pt"
            torch.save({
                "step": step,
                "model_state_dict": model.state_dict(),
                "model_config": cfg.to_dict(),
                "tokenizer": tokenizer.to_str(),
                "stage": "sft"
            }, save_path)
            log(f"  💾 Checkpoint saved: {save_path.name}")

    # Final Save
    torch.save({
        "step": args.max_steps,
        "model_state_dict": model.state_dict(),
        "model_config": cfg.to_dict(),
        "tokenizer": tokenizer.to_str(),
        "stage": "sft"
    }, out_dir / "checkpoint-final.pt")
    log(f"\n🎉 SFT Complete! Best checkpoint saved at '{out_dir}/checkpoint-best.pt'")


if __name__ == "__main__":
    main()

